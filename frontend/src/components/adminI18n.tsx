export function translateAdmin(language: Lang, text: string, values?: Array<string | number | null | undefined>): string {
  const entry = DICT[text]
  let out = language === 'en' || !entry ? text : language === 'kg' ? entry[0] : entry[1]
  if (values) values.forEach((value, index) => { out = out.split(`{${index}}`).join(String(value ?? '')) })
  return out
}

/** `const t = useAdminT()` → `t('English text')` / `t('Edit {0}', [name])`. */
export function useAdminT() {
  const language = useLanguage()
  return useCallback((text: string, values?: Array<string | number | null | undefined>) => translateAdmin(language, text, values), [language])
}

/** KG / RU / EN switcher for the admin pages. Changes the whole interface instantly and is remembered. */
export function AdminLanguageSwitch() {
  const language = useLanguage()
  const setLanguage = useContext(LanguageSetterContext)
  return (
    <div className="admin-lang-switch">
      <LanguageSwitcher language={language} setLanguage={setLanguage} label={translateAdmin(language, 'Language')} />
    </div>
  )
}
