export function seedCoursesAndLessonsIfEmpty(db) {
  const countRow = db.prepare('SELECT COUNT(*) AS count FROM courses').get()
  if (countRow && countRow.count > 0) {
    return
  }

  const nowIso = new Date().toISOString()

  const insertCourseStmt = db.prepare(`
    INSERT INTO courses (
      id, badge, title_kg, title_ru, title_en,
      description_kg, description_ru, description_en,
      category, level, rating, students, duration, lessons_count,
      color, accent, tags, outline, is_published, order_index, created_at, updated_at
    ) VALUES (
      @id, @badge, @title_kg, @title_ru, @title_en,
      @description_kg, @description_ru, @description_en,
      @category, @level, @rating, @students, @duration, @lessons_count,
      @color, @accent, @tags, @outline, @is_published, @order_index, @created_at, @updated_at
    )
  `)

  const insertLessonStmt = db.prepare(`
    INSERT INTO lessons (
      id, course_id, title_kg, title_ru, title_en,
      duration, type, theory, code, task, video_url,
      quiz_json, order_index, is_published, created_at, updated_at
    ) VALUES (
      @id, @course_id, @title_kg, @title_ru, @title_en,
      @duration, @type, @theory, @code, @task, @video_url,
      @quiz_json, @order_index, @is_published, @created_at, @updated_at
    )
  `)

  const seedTransaction = db.transaction(() => {
    for (const c of initialCourses) {
      insertCourseStmt.run({
        ...c,
        created_at: nowIso,
        updated_at: nowIso
      })

      const names = lessonNames[c.id]
      const urls = lessonVideoLibrary[c.id] ?? []

      if (names && names.kg) {
        for (let i = 0; i < names.kg.length; i++) {
          const lessonId = `${c.id}-lesson-${i + 1}`
          const quiz = {
            prompt: {
              kg: 'Сабактын суроосуна туура жооп кайсы?',
              ru: 'Какой ответ на вопрос урока?',
              en: 'What is the correct answer to this lesson question?'
            },
            options: ['Вариант A', 'Вариант B', 'Вариант C', 'Вариант D'],
            answer: (i + 1) % 4
          }

          insertLessonStmt.run({
            id: lessonId,
            course_id: c.id,
            title_kg: `Сабак ${i + 1}. ${names.kg[i]}`,
            title_ru: `Урок ${i + 1}. ${names.ru[i]}`,
            title_en: `Lesson ${i + 1}. ${names.en[i]}`,
            duration: `${35 + ((i * 13) % 28)} мин`,
            type: i % 3 === 0 ? 'Видео + практика' : 'Видеоурок',
            theory: `Изучаем ключевую тему урока ${i + 1} и закрепляем практическое понимание на примерах из реального проекта.`,
            code: `const lesson${i + 1} = () => {\n  const result = 'Урок ${i + 1} готов';\n  console.log(result);\n  return result;\n};`,
            task: `Выполни практическое задание для урока ${i + 1} и проверь результат на примере проекта.`,
            video_url: urls[i] ?? 'https://youtu.be/OLn2xxOF51Y',
            quiz_json: JSON.stringify(quiz),
            order_index: i + 1,
            is_published: 1,
            created_at: nowIso,
            updated_at: nowIso
          })
        }
      }
    }
  })

  seedTransaction()
  console.log('[DB SEED] Successfully seeded 8 courses and 160 lessons into database.')
}
